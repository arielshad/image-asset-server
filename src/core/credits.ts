/**
 * Credits for a set of images: a human ATTRIBUTION.md (grouped by licence,
 * Title / Author / Source / Licence, with the ready-made credit line where the
 * licence asks for one) and a machine-readable credits.json. Downloads and
 * sequences write both next to the files; `mergeCredits` keeps re-writes
 * idempotent (one entry per image id).
 */
import { attributionLine, COMMERCIAL_SAFE, VERDICT_LABELS } from "./licence.js";
import type { ImageAsset, CommercialVerdict } from "./types.js";
import { COMMERCIAL_VERDICTS } from "./types.js";

export interface CreditEntry {
  id: string;
  provider: string;
  source?: string;
  title: string;
  author?: string;
  authorUrl?: string;
  url: string;
  license: {
    id: string;
    name: string;
    url?: string;
    verdict: CommercialVerdict;
    verdictLabel: string;
    attributionRequired: boolean;
    commercialUse?: boolean;
    shareAlike?: boolean;
    editorial?: boolean;
    note?: string;
  };
  /** Credit line to publish with the image; set when the licence asks for attribution. */
  attribution?: string;
  downloadedAt?: string;
  /** Local file(s) the entry describes, when the caller passes them. */
  files?: { path: string; sha256?: string }[];
}

export interface CreditsFile {
  generator: string;
  generatedAt: string;
  notice: string;
  /** True when every image is cleared for commercial use (verdict yes / yes-with-credit). */
  commercialSafe: boolean;
  /** True when at least one image is editorial-only (not for advertising). */
  editorialOnly: boolean;
  /** True when at least one image must be credited. */
  creditsNeeded: boolean;
  images: CreditEntry[];
}

export interface CreditsOptions {
  /** Provider id → display name, for the "Source" column and credit lines. */
  sourceNames?: Record<string, string>;
  /** ISO time for every entry, or per image id. Defaults to now. */
  downloadedAt?: string | Record<string, string>;
  /** Local files per image id. */
  files?: Record<string, { path: string; sha256?: string }[]>;
  /** Timestamp for the header (tests). */
  now?: Date;
}

const NOTICE =
  "Generated by image-asset-server. Licence verdicts are a summary, not legal advice: read each licence before publishing. People, logos and brands in the picture may need releases for advertising. Do not re-upload the images themselves as stock unless their licence allows it.";

const UNKNOWN_LICENSE: CreditEntry["license"] = {
  id: "LicenseRef-Unknown",
  name: "No licence stated",
  verdict: "check-terms",
  verdictLabel: VERDICT_LABELS["check-terms"],
  attributionRequired: false,
};

export function creditEntry(s: ImageAsset, opts: CreditsOptions = {}): CreditEntry {
  const l = s.license;
  const source = opts.sourceNames?.[s.provider];
  const downloadedAt = typeof opts.downloadedAt === "string" ? opts.downloadedAt : (opts.downloadedAt?.[s.id] ?? (opts.downloadedAt ? undefined : (opts.now ?? new Date()).toISOString()));
  const entry: CreditEntry = {
    id: s.id,
    provider: s.provider,
    ...(source ? { source } : {}),
    title: s.title,
    ...(s.author ? { author: s.author } : {}),
    ...(s.authorUrl ? { authorUrl: s.authorUrl } : {}),
    url: s.url,
    license: l
      ? {
          id: l.id,
          name: l.name,
          ...(l.url ? { url: l.url } : {}),
          verdict: l.verdict,
          verdictLabel: VERDICT_LABELS[l.verdict],
          attributionRequired: !!l.attributionRequired,
          ...(l.commercialUse !== undefined ? { commercialUse: l.commercialUse } : {}),
          ...(l.shareAlike ? { shareAlike: true } : {}),
          ...(l.editorial ? { editorial: true } : {}),
          ...(l.note ? { note: l.note } : {}),
        }
      : UNKNOWN_LICENSE,
  };
  const credit = l?.attributionRequired ? (s.attribution ?? attributionLine(s, source)) : undefined;
  if (credit) entry.attribution = credit;
  if (downloadedAt) entry.downloadedAt = downloadedAt;
  const files = opts.files?.[s.id];
  if (files?.length) entry.files = files;
  return entry;
}

/** credits.json content (serialise with JSON.stringify(…, null, 2)). */
export function creditsJson(images: ImageAsset[], opts: CreditsOptions = {}): CreditsFile {
  const entries = uniqueById(images).map((s) => creditEntry(s, opts));
  return summarise(entries, (opts.now ?? new Date()).toISOString());
}

/** Merge new entries into an existing credits.json (same id → the newer entry wins, files are combined). */
export function mergeCredits(existing: CreditsFile | undefined, next: CreditsFile): CreditsFile {
  const byId = new Map<string, CreditEntry>();
  for (const e of existing?.images ?? []) byId.set(e.id, e);
  for (const e of next.images) {
    const old = byId.get(e.id);
    const files = [...(old?.files ?? []), ...(e.files ?? [])].filter((f, i, all) => all.findIndex((g) => g.path === f.path) === i);
    byId.set(e.id, { ...e, downloadedAt: e.downloadedAt ?? old?.downloadedAt, ...(files.length ? { files } : {}) });
  }
  return summarise([...byId.values()], next.generatedAt);
}

function summarise(entries: CreditEntry[], generatedAt: string): CreditsFile {
  return {
    generator: "image-asset-server",
    generatedAt,
    notice: NOTICE,
    commercialSafe: entries.every((e) => COMMERCIAL_SAFE.has(e.license.verdict)),
    editorialOnly: entries.some((e) => e.license.editorial === true),
    creditsNeeded: entries.some((e) => e.license.attributionRequired),
    images: entries,
  };
}

/**
 * ATTRIBUTION.md: a warning header when anything is not commercial-safe, then
 * one section per licence (most permissive first) listing Title, Author,
 * Source and the credit line to publish.
 */
export function creditsMarkdown(images: ImageAsset[], sourceNames?: Record<string, string>, opts?: Omit<CreditsOptions, "sourceNames">): string;
export function creditsMarkdown(entries: CreditsFile): string;
export function creditsMarkdown(input: ImageAsset[] | CreditsFile, sourceNames: Record<string, string> = {}, opts: Omit<CreditsOptions, "sourceNames"> = {}): string {
  const file = Array.isArray(input) ? creditsJson(input, { ...opts, sourceNames }) : input;
  const entries = file.images;
  const lines: string[] = ["# Attribution", ""];
  if (!entries.length) {
    lines.push("No images yet.", "");
    return lines.join("\n");
  }
  const unsafe = entries.filter((e) => !COMMERCIAL_SAFE.has(e.license.verdict));
  if (unsafe.length) {
    lines.push(
      `> **Warning:** ${unsafe.length} of ${entries.length} image${entries.length === 1 ? " is" : "s are"} not cleared for commercial use:`,
      ...unsafe.map((e) => `> - ${e.title} (${e.id}): ${e.license.verdictLabel}`),
      "",
    );
  }
  const editorial = entries.filter((e) => e.license.editorial);
  if (editorial.length) {
    lines.push(
      `> **Editorial use:** ${editorial.length} image${editorial.length === 1 ? " shows" : "s show"} people, insignia or brands without releases. Fine for news, documentary and education; not for ads or anything that implies endorsement:`,
      ...editorial.map((e) => `> - ${e.title} (${e.id})`),
      "",
    );
  }
  const credited = entries.filter((e) => e.attribution);
  if (credited.length) {
    lines.push("## Credits to publish", "", "Paste these next to the images, in captions or on a credits page:", "");
    for (const e of credited) lines.push(`- ${e.attribution}`);
    lines.push("");
  }
  const order = (v: CommercialVerdict) => COMMERCIAL_VERDICTS.indexOf(v);
  const groups = new Map<string, CreditEntry[]>();
  for (const e of [...entries].sort((a, b) => order(a.license.verdict) - order(b.license.verdict) || a.license.name.localeCompare(b.license.name))) {
    const k = e.license.id;
    groups.set(k, [...(groups.get(k) ?? []), e]);
  }
  for (const group of groups.values()) {
    const l = group[0]!.license;
    lines.push(`## ${l.url ? `[${l.name}](${l.url})` : l.name}`, "", `${l.verdictLabel}.${l.attributionRequired ? " Attribution required." : ""}`, "");
    for (const e of group) {
      const author = e.author ? (e.authorUrl ? `[${e.author}](${e.authorUrl})` : e.author) : "unknown author";
      lines.push(`- **${md(e.title)}** by ${author}, ${e.source ?? e.provider}: ${e.url}`);
      lines.push(`  - id: \`${e.id}\`${e.downloadedAt ? `, downloaded ${e.downloadedAt.slice(0, 10)}` : ""}`);
    }
    lines.push("");
  }
  lines.push("---", "", `_${NOTICE}_`, "");
  return lines.join("\n");
}

function md(s: string): string {
  return s.replace(/([*_`[\]])/g, "\\$1");
}

function uniqueById(images: ImageAsset[]): ImageAsset[] {
  const seen = new Set<string>();
  return images.filter((s) => (seen.has(s.id) ? false : (seen.add(s.id), true)));
}
